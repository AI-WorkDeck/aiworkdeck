    @Test void projectSaveHandoffDoesNotAcquireAnotherProjectsLockOrAcknowledgeItsReceipt() throws Exception {
        save("BBBB");
        Path second = Files.createDirectories(root.resolve("projects/202")).resolve("second.txt");
        Files.writeString(second, "1111");
        sql("INSERT INTO project(id,name,project_type,user_id,uid) VALUES(202,'Second','CASE',11,'project-202')");
        sql("INSERT INTO project_file(id,project_id,is_folder,name,file_type,file_size,file_path,user_id,client_visible,is_deleted,uid) VALUES(2002,202,FALSE,'second.txt','txt',4,'projects/202/second.txt',11,FALSE,FALSE,'file-2002')");
        String hash = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(second)));
        content.save(new LocalCoreContentService.SaveRequest(UUID.randomUUID(), 202, 2002, "file-2002", 11, hash, 4),
                new ByteArrayInputStream("2222".getBytes(StandardCharsets.UTF_8)));
        // An unrelated pending project may be invalid; project 101 must neither lock nor process it.
        sql("UPDATE project_file SET uid='reused-id' WHERE id=2002");
        var observed = spy(sessions);
        new LocalCoreVersionHandoff(repos, observed, manifests, lifecycle, projects, files, storage).handoffProject(content, 101);
        verify(observed).runLocked(eq(101L), any(Runnable.class));
        verify(observed, never()).runLocked(eq(202L), any(Runnable.class));
        var pending = content.beforeImagesForHandoff();
        assertEquals(1, pending.size()); assertEquals(202, pending.get(0).request().projectId());
        assertFalse(repos.isInitialized(202)); assertEquals("2222", Files.readString(second));
    }

    @Test void moreThanTwoHundredReceiptsAreAcknowledgedInBoundedBatches() throws Exception {
        save("BBBB");
        var original = content.beforeImagesForHandoff().get(0);
        var images = new ArrayList<LocalCoreContentService.BeforeImage>();
        for (int i = 0; i < 201; i++) {
            var request = new LocalCoreContentService.SaveRequest(UUID.randomUUID(), 101, 1001, "file-1001", 11,
                    original.request().expectedSha256(), original.request().contentLength());
            images.add(new LocalCoreContentService.BeforeImage(i + 1, request, original.storageKey(), original.externalPath(),
                    original.targetPath(), original.beforeSha256(), original.beforeSize(), original.image()));
        }
        // Batch boundaries are unit-checked; actual receipt binding is exercised by the real-content tests above.
        var source = mock(LocalCoreContentService.class);
        when(source.beforeImagesForHandoff()).thenReturn(images);
        handoff(source);
        var batches = org.mockito.ArgumentCaptor.forClass(List.class);
        verify(source, times(2)).acknowledgeHandoff(batches.capture(), startsWith("CREATED:"));
        assertEquals(List.of(200, 1), batches.getAllValues().stream().map(List::size).toList());
        assertEquals("AAAA", new String(repos.readBlobAtCommit(101, "HEAD", "contract.docx"), StandardCharsets.UTF_8));
        assertEquals("BBBB", Files.readString(document));
    }
