    @AfterEach void close() throws Exception { if (database != null) sql("SHUTDOWN"); }

    private void sql(String statement, Object... args) throws Exception {
        try (var c = database.getConnection(); var s = c.prepareStatement(statement)) {
            for (int i = 0; i < args.length; i++) s.setObject(i + 1, args[i]);
            s.executeUpdate();
        }
    }

    private Optional<Project> project(long id) throws Exception {
        try (var c = database.getConnection(); var s = c.prepareStatement("SELECT * FROM project WHERE id=?")) {
            s.setLong(1, id);
            try (var r = s.executeQuery()) {
                if (!r.next()) return Optional.empty();
                var p = new Project(); p.setId(id); p.setName(r.getString("name")); p.setUid(r.getString("uid"));
                p.setUserId(r.getLong("user_id")); p.setProjectType(r.getString("project_type"));
                p.setLocalRoot(r.getString("local_root")); p.setVersionOptOut(r.getObject("version_opt_out", Boolean.class));
                return Optional.of(p);
            }
        }
    }

    private Optional<User> user(long id) throws Exception {
        try (var c = database.getConnection(); var s = c.prepareStatement("SELECT * FROM app_users WHERE id=?")) {
            s.setLong(1, id);
            try (var r = s.executeQuery()) {
                if (!r.next()) return Optional.empty();
                var user = new User(); user.setId(id); user.setUsername(r.getString("username")); user.setDisplayName(r.getString("display_name"));
                return Optional.of(user);
            }
        }
    }

    private List<ProjectFile> projectFiles(long id) throws Exception {
        try (var c = database.getConnection(); var s = c.prepareStatement("SELECT * FROM project_file WHERE project_id=? ORDER BY id")) {
            s.setLong(1, id); var result = new ArrayList<ProjectFile>();
            try (var r = s.executeQuery()) {
                while (r.next()) {
                    var f = new ProjectFile(); f.setId(r.getLong("id")); f.setProjectId(id); f.setUid(r.getString("uid"));
                    f.setName(r.getString("name")); f.setFilePath(r.getString("file_path")); f.setExternalPath(r.getString("external_path"));
                    f.setIsFolder(r.getBoolean("is_folder")); f.setIsDeleted(r.getBoolean("is_deleted"));
                    f.setFileSize(r.getLong("file_size")); f.setFileType(r.getString("file_type")); f.setUserId(r.getLong("user_id"));
                    f.setParentId(r.getObject("parent_id", Long.class)); f.setSortOrder(r.getObject("sort_order", Integer.class)); result.add(f);
                }
            }
            return result;
        }
    }

    private void save(String next) throws Exception {
        String hash = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(document)));
        byte[] bytes = next.getBytes(StandardCharsets.UTF_8);
        content.save(new LocalCoreContentService.SaveRequest(UUID.randomUUID(), 101, 1001, "file-1001", 11, hash, bytes.length),
                new ByteArrayInputStream(bytes));
    }

    private void handoff(LocalCoreContentService source) throws Exception {
        new LocalCoreVersionHandoff(repos, sessions, manifests, lifecycle, projects, files, storage).handoff(source);
    }

    @Test void realReceiptsCreateFirstBeforeHistoryAndAckOnlyAfterTheGitCommit() throws Exception {
        save("BBBB"); save("CCCC");
        handoff(content);
        assertTrue(content.beforeImagesForHandoff().isEmpty());
        assertEquals("AAAA", new String(repos.readBlobAtCommit(101, "HEAD", "contract.docx"), StandardCharsets.UTF_8));
        assertEquals("CCCC", Files.readString(document));
        assertEquals("Actual Author", repos.log(101, "HEAD", 1).get(0).authorName());
        assertEquals("file-1001", manifests.readAtRef(101, "HEAD").nodes().get(0).uid());
        assertFalse(repos.pendingChanges(101).isEmpty());
        assertNotNull(repos.commitAll(101, "saved", "auto", null, "Actual Author", "author@example.test"));
        assertEquals("CCCC", new String(repos.readBlobAtCommit(101, "HEAD", "contract.docx"), StandardCharsets.UTF_8));
        verifyNoInteractions(events, scheduler);
    }

    @Test void existingHeadIsPreservedButReusedFileIdentityMustNotBeAcknowledged() throws Exception {
        repos.init(101, "Original", "original@example.test");
        String head = repos.resolveRef(101, "HEAD");
        save("BBBB");
        sql("UPDATE project_file SET uid='different-file' WHERE id=1001");
        assertThrows(VersionException.class, () -> handoff(content));
        assertEquals(1, content.beforeImagesForHandoff().size());
        assertEquals(head, repos.resolveRef(101, "HEAD"));
        sql("UPDATE project_file SET uid='file-1001' WHERE id=1001");
        handoff(content);
        assertTrue(content.beforeImagesForHandoff().isEmpty());
        assertEquals(head, repos.resolveRef(101, "HEAD"));
        assertEquals(1, repos.log(101, "HEAD", 10).size());
    }

    @Test void optOutAndGlobalDisabledPoliciesAreDurablyAcknowledgedWithoutInitializing() throws Exception {
        save("BBBB"); sql("UPDATE project SET version_opt_out=TRUE WHERE id=101");
        handoff(content);
        assertTrue(content.beforeImagesForHandoff().isEmpty()); assertFalse(repos.isInitialized(101));
        sql("UPDATE project SET version_opt_out=FALSE WHERE id=101");
        save("CCCC"); lifecycle.setAutoEnableForTest(false);
        handoff(content);
        assertTrue(content.beforeImagesForHandoff().isEmpty()); assertFalse(repos.isInitialized(101));
        lifecycle.setAutoEnableForTest(true); save("DDDD"); handoff(content);
        assertEquals("CCCC", new String(repos.readBlobAtCommit(101, "HEAD", "contract.docx"), StandardCharsets.UTF_8));
        assertEquals("DDDD", Files.readString(document));
    }

    @Test void guardrailIncludesLargerBeforeBytesEvenAfterTheCurrentDocumentShrank() throws Exception {
        Files.writeString(document, "a larger original document");
        sql("UPDATE project_file SET file_size=? WHERE id=1001", Files.size(document));
        save("small"); lifecycle.setGuardrailForTest(10, 100);
        handoff(content);
        assertTrue(content.beforeImagesForHandoff().isEmpty()); assertFalse(repos.isInitialized(101));
        assertEquals("small", Files.readString(document));
    }

    @Test void metadataPathChangeAndUnmarkedUnbornRepoFailWithoutAck() throws Exception {
        save("BBBB");
        sql("UPDATE project_file SET file_path='projects/101/reused.docx' WHERE id=1001");
        assertThrows(VersionException.class, () -> handoff(content));
        assertEquals(1, content.beforeImagesForHandoff().size());
        sql("UPDATE project_file SET file_path='projects/101/contract.docx' WHERE id=1001");
        repos.initEmptyForReceive(101);
        assertThrows(VersionException.class, () -> handoff(content));
        assertEquals(1, content.beforeImagesForHandoff().size());
        assertNull(repos.resolveRef(101, "HEAD"));
        assertFalse(Files.exists(root.resolve("projects/101/.awd")), "Do not pollute an intentional receive repository");
    }

    @Test void ackFailureAfterCommitCanRetryWithoutChangingHistory() throws Exception {
        save("BBBB");
        var failing = spy(content);
        doThrow(new IOException("ack unavailable")).when(failing).acknowledgeHandoff(anyList(), anyString());
        assertThrows(VersionException.class, () -> handoff(failing));
        String head = repos.resolveRef(101, "HEAD");
        assertNotNull(head); assertEquals(1, content.beforeImagesForHandoff().size());
        handoff(content);
        assertTrue(content.beforeImagesForHandoff().isEmpty());
        assertEquals(head, repos.resolveRef(101, "HEAD")); assertEquals(1, repos.log(101, "HEAD", 10).size());
    }

