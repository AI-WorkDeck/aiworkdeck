package com.checkba.localcore;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.SQLException;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

class LocalCoreSchemaProofTest {
    private JdbcDataSource source;
    private LocalCoreSchemaProof proof;

    @BeforeEach void setup() {
        source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:core-proof-" + UUID.randomUUID()
                + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;NON_KEYWORDS=VALUE;DB_CLOSE_DELAY=-1");
        proof = new LocalCoreSchemaProof(source, "owned-test-build");
    }

    private void sql(String sql) throws SQLException {
        try (var c = source.getConnection(); var s = c.createStatement()) { s.execute(sql); }
    }

    @AfterEach void closeOwnedDatabase() throws SQLException { sql("SHUTDOWN"); }

    private void schema() throws SQLException {
        sql("CREATE TABLE app_users(id BIGINT PRIMARY KEY, name VARCHAR(100))");
        sql("CREATE TABLE project(id BIGINT PRIMARY KEY, user_id BIGINT REFERENCES app_users(id))");
        sql("CREATE TABLE project_file(id BIGINT PRIMARY KEY, project_id BIGINT REFERENCES project(id), file_size BIGINT DEFAULT 0)");
        sql("CREATE TABLE system_setting(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, config_key VARCHAR(128) NOT NULL UNIQUE, \"value\" TEXT)");
    }

    @Test void noSchemaOrNoSuccessfulInitializationProofCannotEnableFastPath() throws Exception {
        assertFalse(proof.isCurrent());
        assertThrows(IllegalStateException.class, proof::recordAfterLegacyInitialization);
        schema();
        assertFalse(proof.isCurrent());
    }

    @Test void successfulLegacyInitializationIsBoundToCurrentSchemaAndBackendBuild() throws Exception {
        schema(); proof.recordAfterLegacyInitialization();
        assertTrue(proof.isCurrent());
        assertTrue(new LocalCoreSchemaProof(source, "owned-test-build").isCurrent());
        assertFalse(new LocalCoreSchemaProof(source, "different-backend-build").isCurrent());
        assertTrue(proof.isCurrent());
    }

    @Test void ordinaryDataAndIdentitySequenceChangesDoNotInvalidateSchemaProof() throws Exception {
        schema(); proof.recordAfterLegacyInitialization();
        sql("INSERT INTO app_users VALUES(7, 'Synthetic user')");
        sql("INSERT INTO project VALUES(11, 7)");
        sql("INSERT INTO project_file(id,project_id) VALUES(91,11)");
        sql("INSERT INTO system_setting(config_key,\"value\") VALUES('local.identity.selectedUserId','7')");
        sql("UPDATE project_file SET file_size=12345 WHERE id=91");
        assertTrue(proof.isCurrent());
    }

    @Test void schemaChangeRequiresLegacyCompletionAgainRatherThanUpdatingProofOnRead() throws Exception {
        schema(); proof.recordAfterLegacyInitialization();
        sql("ALTER TABLE project_file ADD COLUMN changed VARCHAR(20)");
        assertFalse(proof.isCurrent());
        assertFalse(proof.isCurrent());
        proof.recordAfterLegacyInitialization();
        assertTrue(proof.isCurrent());
    }

    @Test void indexAndDefaultChangesAreIncludedInFingerprint() throws Exception {
        schema(); proof.recordAfterLegacyInitialization();
        sql("CREATE INDEX changed_index ON project_file(file_size)");
        assertFalse(proof.isCurrent());
        proof.recordAfterLegacyInitialization();
        sql("ALTER TABLE project_file ALTER COLUMN file_size SET DEFAULT 8");
        assertFalse(proof.isCurrent());
    }

    @Test void proofCorruptionCannotEnableFastPathOrChangeUnrelatedSettings() throws Exception {
        schema(); proof.recordAfterLegacyInitialization();
        sql("INSERT INTO system_setting(config_key,\"value\") VALUES('unrelated','preserve')");
        sql("UPDATE system_setting SET \"value\"='corrupt' WHERE config_key='local.core.schemaProof'");
        assertFalse(proof.isCurrent());
        try (var c = source.getConnection(); var s = c.createStatement();
             var r = s.executeQuery("SELECT \"value\" FROM system_setting WHERE config_key='unrelated'")) {
            assertTrue(r.next()); assertEquals("preserve", r.getString(1));
        }
    }

    @Test void missingRequiredTableCannotBeBlessedAsCompatible() throws Exception {
        schema(); proof.recordAfterLegacyInitialization();
        sql("DROP TABLE project_file");
        assertFalse(proof.isCurrent());
        assertThrows(IllegalStateException.class, proof::recordAfterLegacyInitialization);
    }

    @Test void buildIdentityMustBeExplicitAndUnambiguous() {
        for (String value : new String[]{null, "", " ", "build\nother", "build\rother", "a".repeat(257)}) {
            assertThrows(IllegalArgumentException.class, () -> new LocalCoreSchemaProof(source, value));
        }
    }

    @Test void checkConstraintChangesInvalidateProof() throws Exception {
        schema();
        sql("ALTER TABLE project_file ADD CONSTRAINT size_nonnegative CHECK(file_size >= 0)");
        proof.recordAfterLegacyInitialization();
        sql("ALTER TABLE project_file DROP CONSTRAINT size_nonnegative");
        assertFalse(proof.isCurrent());
    }

    @Test void identityGenerationRulesAreStaticSchema() throws Exception {
        schema(); proof.recordAfterLegacyInitialization();
        sql("ALTER TABLE system_setting ALTER COLUMN id SET GENERATED ALWAYS");
        assertFalse(proof.isCurrent());
    }

    @Test void unsupportedViewCannotReceiveACompatibleProof() throws Exception {
        schema(); sql("CREATE VIEW custom_view AS SELECT id FROM project");
        assertThrows(IllegalStateException.class, proof::recordAfterLegacyInitialization);
        assertFalse(proof.isCurrent());
    }

    @Test void unsupportedGeneratedColumnCannotReceiveACompatibleProof() throws Exception {
        schema(); sql("ALTER TABLE project_file ADD doubled BIGINT GENERATED ALWAYS AS (file_size * 2)");
        assertThrows(IllegalStateException.class, proof::recordAfterLegacyInitialization);
        assertFalse(proof.isCurrent());
    }
}
