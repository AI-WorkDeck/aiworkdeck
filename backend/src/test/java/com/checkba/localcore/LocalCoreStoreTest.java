    @Test void identitySelectionWaitsUntilLockedPublicationAndMetadataCommit() throws Exception {
        var pool = Executors.newSingleThreadExecutor();
        try (Connection c = database.getConnection()) {
            c.setAutoCommit(false);
            var target = store.lockFileTargetForWrite(c, 101, 1001);
            var selecting = new CountDownLatch(1);
            var switched = pool.submit(() -> {
                selecting.countDown(); return store.selectIdentity(22);
            });
            assertTrue(selecting.await(2, TimeUnit.SECONDS));
            assertThrows(TimeoutException.class, () -> switched.get(100, TimeUnit.MILLISECONDS));
            assertEquals(11, target.actor().id());
            Files.writeString(target.path(), "saved before identity switch");
            assertEquals(1, store.updateContentMetadata(c, target, Files.size(target.path()), MODIFIED));
            assertThrows(TimeoutException.class, () -> switched.get(100, TimeUnit.MILLISECONDS));
            c.commit();
            assertEquals(22L, switched.get(2, TimeUnit.SECONDS).userId());
            assertEquals(Files.size(target.path()), scalar("SELECT file_size FROM project_file WHERE id=1001"));
            assertEquals("saved before identity switch", Files.readString(target.path()));
            assertEquals(22, store.currentActor().id());
        } finally { pool.shutdownNow(); }
    }

