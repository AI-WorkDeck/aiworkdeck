    @Test void permanentlyHeldNativeEmfLeavesRealJdbcCoreUsableThenDrainsBeforeBusinessInitialization() throws Exception {
        Fixture fixture = new Fixture(true, true); fixture.prepare();
        GenericApplicationContext context = fixture.context();
        new AnnotatedBeanDefinitionReader(context).register(DataSourceConfiguration.class);
        CountDownLatch emfEntered = new CountDownLatch(1), allowEmf = new CountDownLatch(1), business = new CountDownLatch(1);
        var bootstrapExecutor = new SimpleAsyncTaskExecutor("owned-emf-");
        resources.add(bootstrapExecutor);
        context.registerBean("entityManagerFactory", LocalContainerEntityManagerFactoryBean.class, () -> {
            var factory = new LocalContainerEntityManagerFactoryBean() {
                @Override protected EntityManagerFactory createNativeEntityManagerFactory() {
                    emfEntered.countDown();
                    try { assertTrue(allowEmf.await(15, TimeUnit.SECONDS)); }
                    catch (InterruptedException e) { Thread.currentThread().interrupt(); throw new IllegalStateException(e); }
                    return super.createNativeEntityManagerFactory();
                }
            };
            factory.setDataSource(context.getBean(DataSource.class));
            factory.setJpaVendorAdapter(new HibernateJpaVendorAdapter());
            factory.setManagedTypes(PersistenceManagedTypes.of());
            factory.setJpaPropertyMap(Map.of("hibernate.hbm2ddl.auto", "none"));
            factory.setBootstrapExecutor(bootstrapExecutor);
            return factory;
        });
        context.registerBean("ownedGate", SmartInitializingSingleton.class, () -> () -> {
            fixture.bootstrap.beforeJpaBusinessInitialization(context, Duration.ofSeconds(3));
            business.countDown();
        });
        var executor = Executors.newSingleThreadExecutor();
        try {
            var refresh = executor.submit(context::refresh);
            try {
                assertTrue(emfEntered.await(5, TimeUnit.SECONDS));
                assertEquals(LocalCoreOwnership.State.CORE, fixture.capture.ownership.state());
                try (var lease = fixture.capture.ownership.acquireCoreLease()) {
                    assertEquals(7L, fixture.capture.store.selectIdentity(7).userId());
                    assertEquals(7L, fixture.capture.store.identityStatus().userId());
                }
                assertEquals(1, business.getCount()); assertFalse(refresh.isDone());
                var lease = fixture.capture.ownership.acquireCoreLease();
                allowEmf.countDown();
                long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(10);
                while (fixture.capture.ownership.state() == LocalCoreOwnership.State.CORE && System.nanoTime() < deadline) Thread.sleep(10);
                assertEquals(LocalCoreOwnership.State.DRAINING, fixture.capture.ownership.state());
                assertEquals(1, business.getCount()); assertEquals(0, fixture.capture.handedOff);
                lease.close(); refresh.get(5, TimeUnit.SECONDS);
                assertEquals(LocalCoreOwnership.State.JPA, fixture.capture.ownership.state());
                assertEquals(0, business.getCount()); assertEquals(1, fixture.capture.handedOff);
                assertSame(fixture.capture.pool, context.getBean(DataSource.class));
                assertEquals(1, context.getBeansOfType(DataSource.class).size());
                assertTrue(new LocalCoreSchemaProof(fixture.capture.pool, BUILD).isCurrent());
            } finally { allowEmf.countDown(); }
        } finally { executor.shutdownNow(); }
        context.close(); assertEquals(1, fixture.capture.closed); assertTrue(fixture.capture.pool.isClosed());
    }

