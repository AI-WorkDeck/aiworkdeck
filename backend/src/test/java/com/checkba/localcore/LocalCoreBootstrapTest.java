    /** Runs in another JVM: the test must not mistake H2's in-process connection sharing for exclusivity. */
    public static final class DatabaseProcess {
        public static void main(String[] args) throws Exception {
            try (var connection = DriverManager.getConnection(args[1], "sa", "")) {
                try (var statement = connection.createStatement(); var result = statement.executeQuery("SELECT 1")) {
                    if (!result.next()) throw new IllegalStateException("Missing owned probe result");
                }
                System.out.println("OPEN"); System.out.flush();
                if (args[0].equals("hold")) System.in.read();
            } catch (SQLException denied) {
                System.out.println("DENIED:" + denied.getErrorCode()); System.exit(2);
            }
        }
    }

    private static Process databaseProcess(String mode, String url) throws Exception {
        String java = Path.of(System.getProperty("java.home"), "bin", "java").toString();
        String classpath = System.getProperty("surefire.test.class.path", System.getProperty("java.class.path"));
        return new ProcessBuilder(java, "-cp", classpath, DatabaseProcess.class.getName(), mode, url)
                .redirectError(ProcessBuilder.Redirect.INHERIT).start();
    }

    private static String status(Process process) throws Exception {
        return CompletableFuture.supplyAsync(() -> {
            try { return new BufferedReader(new InputStreamReader(process.getInputStream())).readLine(); }
            catch (java.io.IOException e) { throw new java.io.UncheckedIOException(e); }
        }).get(10, TimeUnit.SECONDS);
    }

    private static void release(Process process) throws Exception {
        try {
            if (process.isAlive()) { process.getOutputStream().write('\n'); process.getOutputStream().flush(); }
            assertTrue(process.waitFor(10, TimeUnit.SECONDS), "Owned database process did not exit");
        } finally { if (process.isAlive()) process.destroyForcibly().waitFor(); }
    }

    private String legacyAutoServerUrl(Fixture fixture) {
        String url = fixture.source.getURL().replace(";DB_CLOSE_ON_EXIT=FALSE", "") + ";AUTO_SERVER=TRUE";
        fixture.source.setURL(url); fixture.properties.put("spring.datasource.url", url);
        return url;
    }

    @Test void runningLegacyProcessPreventsEarlyCoreInsteadOfAttachingToItsAutoServer() throws Exception {
        Fixture fixture = new Fixture(true, true);
        String url = legacyAutoServerUrl(fixture);
        Process legacy = databaseProcess("hold", url);
        try {
            assertEquals("OPEN", status(legacy));
            fixture.prepare();
            assertEquals(0, fixture.capture.prepared, "Early core must not share a database owned by another JVM");
            assertEquals(url, fixture.env.getProperty("spring.datasource.url"));
            assertEquals("update", fixture.env.getProperty("spring.jpa.hibernate.ddl-auto"));
        } finally { fixture.bootstrap.close(); release(legacy); }
    }

    @Test void earlyCoreExclusivelyOwnsFileEvenAgainstAnUnmodifiedLegacyProcessAndReleasesItOnClose() throws Exception {
        Fixture fixture = new Fixture(true, true);
        String url = legacyAutoServerUrl(fixture);
        fixture.prepare();
        assertEquals(1, fixture.capture.prepared);
        assertEquals(url, fixture.env.getProperty("spring.datasource.url"), "Original legacy configuration must be unchanged");
        assertTrue(fixture.capture.pool.getJdbcUrl().contains(";AUTO_SERVER=FALSE;"));
        Process legacy = databaseProcess("probe", url);
        try {
            assertEquals("DENIED:90020", status(legacy));
            assertTrue(legacy.waitFor(5, TimeUnit.SECONDS)); assertEquals(2, legacy.exitValue());
        } finally { release(legacy); }
        fixture.bootstrap.close();
        Process afterClose = databaseProcess("probe", url);
        try {
            assertEquals("OPEN", status(afterClose));
            assertTrue(afterClose.waitFor(5, TimeUnit.SECONDS)); assertEquals(0, afterClose.exitValue());
        } finally { release(afterClose); }
    }
