    /** Deliberately avoids shutdown hooks and JDBC cleanup at each durable boundary. */
    public static final class HaltWriter {
        public static void main(String[] args) throws Exception {
            var source = new JdbcDataSource(); source.setURL(args[0]);
            requireWriteDelay(source, "500");
            Path root = Path.of(args[1]); Path journal = Path.of(args[2]);
            var point = LocalCoreContentService.FaultPoint.valueOf(args[3]);
            var request = new LocalCoreContentService.SaveRequest(UUID.fromString(args[4]), 101, 1001, UID,
                    11, hash(ORIGINAL), bytes(SAVED).length);
            var service = new LocalCoreContentService(source, new LocalCoreStore(source, root), journal,
                    DATABASE_ID, 1024 * 1024, at -> {
                if (at == point) {
                    requireWriteDelay(source, "0");
                    System.out.println("HALTING " + point); System.out.flush(); Runtime.getRuntime().halt(71);
                }
            });
            if (point == AFTER_CANCEL_COMMIT) service.cancel(request);
            else save(service, request, SAVED);
            throw new AssertionError("Requested halt point was never reached");
        }
        private static void requireWriteDelay(JdbcDataSource source, String expected) throws IOException {
            try (var c = source.getConnection(); var s = c.createStatement();
                 var r = s.executeQuery("SELECT setting_value FROM information_schema.settings WHERE setting_name='WRITE_DELAY'")) {
                if (!r.next() || !expected.equals(r.getString(1))) throw new AssertionError("Expected WRITE_DELAY=" + expected);
            } catch (SQLException failure) { throw new IOException(failure); }
        }
    }

    private LocalCoreContentService service(LocalCoreContentService.FaultInjector faults) throws IOException {
        return new LocalCoreContentService(database, store, journal, DATABASE_ID, 1024 * 1024, faults);
    }
    private record MacMetadata(Map<String, String> xattrs, List<String> acl, FileTime created,
                               String permissions, String owner, String group) {}
    private MacMetadata attachMacMetadata() throws Exception {
        org.junit.jupiter.api.Assumptions.assumeTrue(System.getProperty("os.name").startsWith("Mac"));
        Files.setPosixFilePermissions(document, PosixFilePermissions.fromString("rw-r-----"));
        nativeCommand("/bin/chmod", "+a", "everyone deny execute", document.toString());
        nativeCommand("/usr/bin/xattr", "-w", "com.aiworkdeck.fixture", "custom-value", document.toString());
        nativeCommand("/usr/bin/xattr", "-wx", "com.apple.metadata:_kMDItemUserTags",
                "62706c6973743030a1015f100f576f726b4465636b20746573740a36080a000000000000010100000000000000020000000000000000000000000000001c", document.toString());
        Files.getFileAttributeView(document, BasicFileAttributeView.class).setTimes(
                FileTime.from(java.time.Instant.parse("2020-01-02T03:04:05Z")), null,
                FileTime.from(java.time.Instant.parse("2019-01-02T03:04:05Z")));
        var metadata = macMetadata(document);
        assertTrue(metadata.acl().stream().anyMatch(line -> line.contains("deny execute")));
        assertTrue(metadata.xattrs().containsKey("com.apple.metadata:_kMDItemUserTags"));
        return metadata;
    }
    private static MacMetadata macMetadata(Path path) throws Exception {
        Map<String, String> attributes = new TreeMap<>();
        for (String name : nativeCommand("/usr/bin/xattr", path.toString()).lines().toList()) {
            attributes.put(name, nativeCommand("/usr/bin/xattr", "-px", name, path.toString()).replaceAll("\\s", ""));
        }
        var posix = Files.readAttributes(path, PosixFileAttributes.class);
        return new MacMetadata(attributes, nativeCommand("/bin/ls", "-lde", path.toString()).lines().skip(1).toList(),
                posix.creationTime(), PosixFilePermissions.toString(posix.permissions()), posix.owner().getName(), posix.group().getName());
    }
    private static String nativeCommand(String... command) throws Exception {
        var process = new ProcessBuilder(command).redirectErrorStream(true).start();
        try {
            assertTrue(process.waitFor(5, TimeUnit.SECONDS), "Native fixture command timed out");
            String output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            assertEquals(0, process.exitValue(), output);
            return output;
        } finally {
            if (process.isAlive()) { process.destroyForcibly(); assertTrue(process.waitFor(5, TimeUnit.SECONDS)); }
        }
    }
    private void crashAt(LocalCoreContentService.FaultPoint point, LocalCoreContentService.SaveRequest request) throws Exception {
        content = service(at -> { if (at == point) throw new SimulatedCrash(); });
        assertThrows(SimulatedCrash.class, () -> save(content, request, SAVED));
    }
    private void restart() throws Exception { execute("SHUTDOWN"); content = service(point -> {}); }
    private static final class SimulatedCrash extends Error {}
    private static LocalCoreContentService.SaveReceipt save(LocalCoreContentService content, LocalCoreContentService.SaveRequest request, String body) throws Exception {
        return content.save(request, new ByteArrayInputStream(bytes(body)));
    }
    private static LocalCoreContentService.SaveRequest request(String before, String after) throws Exception {
        return new LocalCoreContentService.SaveRequest(UUID.randomUUID(), 101, 1001, UID, 11, hash(before), bytes(after).length);
    }
    private static byte[] bytes(String content) { return content.getBytes(StandardCharsets.UTF_8); }
    private static String hash(String content) throws Exception { return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes(content))); }
    private long receiptCount() throws SQLException { return ((Number) scalar("SELECT COUNT(*) FROM system_setting WHERE config_key LIKE 'local.core.save.%'")).longValue(); }
    private void execute(String sql, Object... values) throws SQLException {
        try (var c = database.getConnection(); var s = c.prepareStatement(sql)) {
            for (int i = 0; i < values.length; i++) s.setObject(i + 1, values[i]); s.execute();
        }
    }
    private Object scalar(String sql) throws SQLException {
        try (var c = database.getConnection(); var s = c.createStatement(); var r = s.executeQuery(sql)) { assertTrue(r.next()); return r.getObject(1); }
    }
    private void sqlUnchecked(String sql) { try { execute(sql); } catch (SQLException e) { throw new IllegalStateException(e); } }
    private static void await(CountDownLatch latch) {
        try { if (!latch.await(5, TimeUnit.SECONDS)) throw new AssertionError("Latch was not released"); }
        catch (InterruptedException interrupted) { Thread.currentThread().interrupt(); throw new AssertionError(interrupted); }
    }
