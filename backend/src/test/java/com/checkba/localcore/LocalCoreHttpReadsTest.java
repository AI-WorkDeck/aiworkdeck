    @Test void headValidatesLikeGetAndUnsupportedRoutesAreNotInvented() throws Exception {
        var head = reads.handle(new LocalCoreHttpReads.Request("HEAD", "/api/files/1001/download", null, Map.of())).orElseThrow();
        assertEquals(get("/api/files/1001/download", null), head);
        store.selectIdentity(55);
        assertEquals(403, reads.handle(new LocalCoreHttpReads.Request("HEAD", "/api/files/1001/download", null, Map.of())).orElseThrow().status());
        for (String path : List.of("/api/desktop/health", "/api/ai/conversations", "/api/projects/101/files/changes", "/api/files/1001/upload")) {
            assertTrue(reads.handle(new LocalCoreHttpReads.Request("GET", path, null, Map.of())).isEmpty(), path);
        }
        assertTrue(reads.handle(new LocalCoreHttpReads.Request("POST", "/api/local-identity/select", null, Map.of())).isEmpty());
        assertTrue(reads.handle(new LocalCoreHttpReads.Request("POST", "/api/projects/my", null, Map.of())).isEmpty());
        assertThrows(IllegalArgumentException.class, () -> new LocalCoreHttpReads(store, database,
                new LicenseService(false, site, directory.toString(), true, ""), account, site,
                new LocalCoreHttpReads.AuthFlags(false, false, false), name -> name));
    }

    private LocalCoreHttpReads adapter(LocalCoreHttpReads.AuthFlags flags) {
        return new LocalCoreHttpReads(store, database, license, account, site, flags,
                name -> "本机用户".equals(name) ? "Local user" : name);
    }
    private LocalCoreHttpReads.Response get(String path, String query) throws SQLException {
        return reads.handle(new LocalCoreHttpReads.Request("GET", path, query, Map.of())).orElseThrow();
    }
    private static Map<?, ?> json(LocalCoreHttpReads.Response response) { assertNull(response.bodyFile()); return (Map<?, ?>) response.jsonBody(); }
    private void connectedAccount() throws Exception {
        Files.writeString(directory.resolve("account.json"), "{\"key\":\"awdk_synthetic-fixture\",\"accountId\":\"machine-account\"}");
    }
    private void file(long id, long projectId, long userId, String name, boolean visible) throws Exception {
        String key = "projects/" + projectId + "/" + id + ".docx";
        execute("INSERT INTO project_file(id,project_id,parent_id,is_folder,name,file_type,file_size,file_path,sort_order,user_id,client_visible,is_deleted,uid) VALUES(?,?,NULL,FALSE,?,'docx',13,?,0,?,?,FALSE,?)",
                id, projectId, name, key, userId, visible, "file-" + id);
        Files.writeString(root.resolve(key), "contents-" + id);
    }
    private void execute(String sql, Object... values) throws SQLException {
        try (var c = database.getConnection(); var s = c.prepareStatement(sql)) {
            for (int i = 0; i < values.length; i++) s.setObject(i + 1, values[i]); s.execute();
        }
    }
    private Object scalar(String sql) throws SQLException {
        try (var c = database.getConnection(); var s = c.createStatement(); var r = s.executeQuery(sql)) { assertTrue(r.next()); return r.getObject(1); }
    }
