import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
const root = fileURLToPath(new URL('../', import.meta.url))
const ids = ['theme-inkwash-zen', 'theme-anime-twilight', 'theme-aurora-glass']
for (const id of ids) {
  const base = path.join(root, 'official-plugins', id)
  const dictionaries = Object.fromEntries(readdirSync(path.join(base, 'l10n')).filter(f => f.endsWith('.json')).sort()
    .map(file => [file.slice(0, -5), JSON.parse(readFileSync(path.join(base, 'l10n', file), 'utf8'))]))
  writeFileSync(path.join(base, 'web', 'awd-plugin-sdk.js'), readFileSync(path.join(root, 'sdk/plugin-sdk/awd-plugin-sdk.js')))
  writeFileSync(path.join(base, 'web', 'gallery.js'), readFileSync(path.join(root, 'scripts/theme-gallery-runtime.js')))
  writeFileSync(path.join(base, 'web', 'gallery-l10n.js'), '// SPDX-FileCopyrightText: 2026 北京京微资易科技有限公司 and AI WorkDeck contributors\n// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by scripts/sync-theme-assets.mjs from l10n/*.json.\nwindow.AWD_THEME_L10N = ' + JSON.stringify(dictionaries, null, 2) + ';\n')
}
