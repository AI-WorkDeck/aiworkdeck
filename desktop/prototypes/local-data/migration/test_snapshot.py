def run_java(name, *args):
    return subprocess.run([str(JAVA / 'java'), '-cp', CP, name, *map(str, args)],
                          capture_output=True, text=True, timeout=30)


class SnapshotTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        OUT.mkdir(parents=True, exist_ok=False)
        (OUT / 'classes').mkdir()
        fixture = OUT / 'SnapshotFixture.java'
        fixture.write_text(FIXTURE)
        subprocess.run([str(JAVA / 'javac'), '-cp', CP, '-d', str(OUT / 'classes'),
                        str(ROOT / 'H2Snapshot.java'), str(fixture)], check=True, capture_output=True, text=True)

    def seed(self, name):
        base = OUT / name
        result = run_java('SnapshotFixture', base)
        self.assertEqual(result.returncode, 0, result.stderr)
        return Path(str(base) + '.mv.db')

    def test_exact_values_schema_and_unchanged_source(self):
        source = self.seed('values')
        before = hashlib.sha256(source.read_bytes()).hexdigest()
        target = OUT / 'export-values'
        result = run_java('H2Snapshot', source, target)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(hashlib.sha256(source.read_bytes()).hexdigest(), before)
        self.assertFalse((target / 'snapshot.jsonl.pending').exists())
        records = [json.loads(line) for line in (target / 'snapshot.jsonl').read_text().splitlines()]
        self.assertEqual(records[0]['sourceSha256'], before)
        self.assertEqual(records[-1]['kind'], 'complete')
        self.assertEqual(records[-1]['counts'], {'empty_table': 0, 'project': 1, 'project_file': 1})
        row = next(r['values'] for r in records if r['kind'] == 'row' and r['table'] == 'project_file')
        self.assertEqual(row['id'], '71')
        self.assertEqual(row['project_id'], '9007199254740993')
        self.assertEqual(row['name'], '合同.docx')
        self.assertEqual(row['amount'], '12345678901234567890.123456789012345678')
        self.assertEqual(row['payload'], 'AAH/')
        self.assertEqual(row['changed'], '2026-10-25 00:00:00.123456789')
        self.assertIsNone(row['extra'])
        self.assertEqual(row['active'], 'TRUE')
        self.assertEqual(json.loads(row['meta_json']), {'text': '中文'})
        table = next(r for r in records if r['kind'] == 'table' and r['name'] == 'project_file')
        self.assertEqual(table['primaryKeys'][0]['COLUMN_NAME'], 'id')
        self.assertEqual(table['foreignKeys'][0]['PKTABLE_NAME'], 'project')
        self.assertTrue(any(r['kind'] == 'source-ddl' and 'FOREIGN KEY' in r['sql'] for r in records))

    @unittest.skipUnless(os.environ.get('SWIFT_BINARY'), 'SWIFT_BINARY required for real H2-to-Swift clone')
    def test_purged_identity_high_water_survives_real_clone(self):
        source_root = OUT / 'identity-source'
        source_root.mkdir()
        (source_root / 'a.txt').write_bytes(b'alpha')
        base = OUT / 'identity'
        seeded = run_java('SnapshotFixture', base, 'identity', source_root)
        self.assertEqual(seeded.returncode, 0, seeded.stderr)
        source = Path(str(base) + '.mv.db')
        before = hashlib.sha256(source.read_bytes()).hexdigest()
        exported = OUT / 'identity-export'
        result = run_java('H2Snapshot', source, exported)
        self.assertEqual(result.returncode, 0, result.stderr)
        roots = OUT / 'identity-roots.json'
        roots.write_text(json.dumps({'1': str(source_root)}))
        profile = OUT / 'identity-clone'
        clone = subprocess.run([sys.executable, '-B', str(ROOT / 'clone_snapshot.py'),
                                '--snapshot', str(exported / 'snapshot.jsonl'),
                                '--project-roots', str(roots), '--output', str(profile),
                                '--binary', os.environ['SWIFT_BINARY']],
                               capture_output=True, text=True, timeout=90)
        self.assertEqual(clone.returncode, 0, clone.stdout + clone.stderr)
        requests = [
            {'id': 1, 'method': 'projects.create', 'params': {'name': '迁移后新项目'}},
            {'id': 2, 'method': 'files.create', 'params': {'projectId': 1, 'name': 'new.txt',
                 'contentBase64': base64.b64encode(b'new').decode()}},
            {'id': 3, 'method': 'files.read', 'params': {'projectId': 1, 'fileId': 11}},
        ]
        env = dict(os.environ)
        env['HOME'] = str(OUT / 'identity-home')
        Path(env['HOME']).mkdir()
        swift = subprocess.run([os.environ['SWIFT_BINARY'], '--profile', str(profile)],
                               input=''.join(json.dumps(request) + '\n' for request in requests),
                               capture_output=True, text=True, timeout=30, env=env)
        self.assertEqual(swift.returncode, 0, swift.stderr)
        responses = [json.loads(line) for line in swift.stdout.splitlines()]
        self.assertEqual([r['id'] for r in responses], [1, 2, 3])
        self.assertTrue(all('result' in r for r in responses), responses)
        self.assertEqual(responses[0]['result']['id'], 901, 'must not reuse physically purged project IDs')
        self.assertEqual(responses[1]['result']['id'], 1501, 'must not reuse physically purged file IDs')
        self.assertEqual(base64.b64decode(responses[2]['result']['contentBase64']), b'alpha')
        self.assertEqual(responses[2]['result']['uid'], 'live-file')
        self.assertEqual(hashlib.sha256(source.read_bytes()).hexdigest(), before)
        self.assertEqual((source_root / 'a.txt').read_bytes(), b'alpha')

    def test_live_database_refused_without_published_snapshot(self):
        source = self.seed('live')
        process = subprocess.Popen([str(JAVA / 'java'), '-cp', CP, 'SnapshotFixture',
                                    str(source)[:-6], 'hold'], stdin=subprocess.PIPE,
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        try:
            self.assertEqual(process.stdout.readline().strip(), 'HOLDING')
            target = OUT / 'export-live'
            result = run_java('H2Snapshot', source, target)
            self.assertNotEqual(result.returncode, 0)
            self.assertFalse((target / 'snapshot.jsonl').exists())
            self.assertIn('already in use', result.stderr)
        finally:
            process.communicate('\n', timeout=10)
            self.assertEqual(process.returncode, 0)

    def test_missing_database_is_not_created(self):
        source = OUT / 'missing.mv.db'
        result = run_java('H2Snapshot', source, OUT / 'export-missing')
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(source.exists())

    def test_existing_destination_not_overwritten(self):
        source = self.seed('existing')
        target = OUT / 'existing-destination'
        target.mkdir()
        sentinel = target / 'snapshot.jsonl'
        sentinel.write_text('preserve')
        result = run_java('H2Snapshot', source, target)
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(sentinel.read_text(), 'preserve')

    def test_symlink_and_jdbc_options_refused(self):
        source = self.seed('path')
        alias = OUT / 'alias.mv.db'
        alias.symlink_to(source)
        for index, path in enumerate([alias, OUT / 'path;IFEXISTS=FALSE.mv.db']):
            result = run_java('H2Snapshot', path, OUT / f'export-path-{index}')
            self.assertNotEqual(result.returncode, 0)


if __name__ == '__main__':
    unittest.main(verbosity=2)
