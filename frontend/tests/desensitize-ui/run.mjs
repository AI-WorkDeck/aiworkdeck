import { fileURLToPath } from "node:url";
import { createHash } from 'node:crypto';
import { mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { join, resolve, extname } from 'node:path';
import { createServer } from 'node:http';
import { spawn } from 'node:child_process';
import assert from 'node:assert/strict';
const frontend = fileURLToPath(new URL('../../', import.meta.url));
const {
  buildHarness
} = await import(frontend + '/tests/tts-panel-ui/build.mjs');
const {
  default: puppeteer
} = await import(frontend + '/node_modules/puppeteer-core/lib/esm/puppeteer/puppeteer-core.js');
const output = resolve(process.argv[2] || '/tmp/awd-panel-1537-desensitize-ui');
await mkdir(output, {
  recursive: true
});
const built = await buildHarness(output);
await writeFile(join(output, 'build.json'), JSON.stringify({
  compiler: '@dcloudio/vite-plugin-uni',
  sourceHash: createHash('sha256').update(await readFile(join(frontend, 'src/components/DesensitizePane.vue'))).digest('hex')
}, null, 2));
const fixture = `<template><view class="qa-root"><DesensitizePane ref="pane" :project-id="1" :prepare-file="prepare" @request-active-file="select" /></view></template>
<script>import DesensitizePane from '@/components/DesensitizePane.vue';export default{components:{DesensitizePane},mounted(){window.__de=this.$refs.pane;document.documentElement.dataset.theme=new URLSearchParams(location.search).get('theme')||'light'},methods:{prepare:async()=>false,select(callback){callback({id:1,name:'合成核验材料的较长文件名.docx',filePath:'/synthetic/test.docx'})}}}</script>
<style>.qa-root{width:100%;height:100vh;background:var(--awd-bg)}</style>`;
await writeFile(join(built.workspace, 'src/pages/tts/index.vue'), fixture);
await writeFile(join(built.workspace, 'src/services/api.js'), `export const getSensitiveOptions=async()=>[{value:'PHONE',label:'手机号 (138****1234)'},{value:'CHINESE_NAME',label:'中文姓名'},{value:'ID_CARD',label:'身份证号 (3301**********1234)'}];export const previewSensitiveFile=async()=>({text:'合成预览：联系人[姓名1]，电话[电话1]',counts:{PHONE:1}});export const desensitizeFile=async()=>({});export const restoreSensitiveFile=async()=>({});`);
// Override the API fixture mapping generated by the shared harness.
let config = await readFile(join(built.workspace, 'vite.config.mjs'), 'utf8');
config = config.replaceAll(join(frontend, 'tests/tts-panel-ui/api.js'), join(built.workspace, 'src/services/api.js'));
await writeFile(join(built.workspace, 'vite.config.mjs'), config);
const compile = spawn(process.execPath, [join(frontend, 'node_modules/@dcloudio/vite-plugin-uni/bin/uni.js'), 'build', '-p', 'h5', '--config', join(built.workspace, 'vite.config.mjs')], {
  cwd: built.workspace,
  env: {
    ...process.env,
    UNI_INPUT_DIR: join(built.workspace, 'src'),
    UNI_OUTPUT_DIR: built.dist,
    UNI_PLATFORM: 'h5'
  },
  stdio: ['ignore', 'pipe', 'pipe']
});
let log = '';
compile.stdout.on('data', d => log += d);
compile.stderr.on('data', d => log += d);
const code = await new Promise(r => compile.on('exit', r));
await writeFile(join(output, 'uni-build.log'), log);
assert.equal(code, 0);
const server = createServer(async (req, res) => {
  try {
    const path = resolve(built.dist, '.' + (req.url.split('?')[0] === '/' ? '/index.html' : req.url.split('?')[0]));
    if (!path.startsWith(built.dist + '/')) throw Error();
    const data = await readFile(path);
    res.setHeader('Content-Type', {
      '.html': 'text/html',
      '.js': 'application/javascript',
      '.css': 'text/css'
    }[extname(path)] || 'application/octet-stream');
    res.end(data);
  } catch {
    res.writeHead(404).end();
  }
});
await new Promise(r => server.listen(0, '127.0.0.1', r));
const origin = 'http://127.0.0.1:' + server.address().port;
const browser = await puppeteer.launch({
  executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  headless: true
});
const page = await browser.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.setRequestInterception(true);
page.on('request', r => r.url().startsWith(origin + '/') || /^(blob:|data:)/.test(r.url()) ? r.continue() : r.abort());
const results = [];
try {
  for (const width of [220, 260, 420]) for (const theme of ['light', 'dark']) {
    await page.setViewport({
      width,
      height: 900
    });
    await page.goto(origin + '/?theme=' + theme + '#/pages/tts/index', {
      waitUntil: 'networkidle0'
    });
    await page.waitForFunction(() => window.__de?.availableStrategies.length === 3);
    await page.click('.file-actions .mini-btn:first-child');
    await page.waitForFunction(() => window.__de.fileId === 1);
    await page.click('.custom-words-toggle');
    await page.click('.settings-section .settings-toggle');
    const geometry = await page.evaluate(() => {
      const pane = document.querySelector('.desensitize-pane');
      const probe = document.createElement('div');
      probe.style.color = 'var(--awd-bg)';
      document.body.append(probe);
      const expected = getComputedStyle(probe).color;
      probe.remove();
      return {
        scroll: document.documentElement.scrollWidth,
        width: innerWidth,
        background: getComputedStyle(pane).backgroundColor,
        expected,
        fileGap: document.querySelector('.file-actions').getBoundingClientRect().top - document.querySelector('.path-display').getBoundingClientRect().bottom,
        controls: [...document.querySelectorAll('.mini-btn,.workdeck-btn,.settings-toggle,.strategy-label,.text-input')].filter(e => e.getBoundingClientRect().width > 0).map(e => {
          const r = e.getBoundingClientRect();
          return {
            left: r.left,
            right: r.right,
            height: r.height,
            scroll: e.scrollWidth,
            width: e.clientWidth,
            class: e.className
          };
        })
      };
    });
    assert.equal(geometry.background, geometry.expected);
    assert(geometry.scroll <= width + 1);
    assert(geometry.fileGap >= 7);
    assert(geometry.controls.every(c => c.left >= -1 && c.right <= width + 1));
    await page.screenshot({
      path: join(output, `${width}-${theme}-expanded.png`)
    });
    await page.click('.workdeck-btn');
    await page.waitForSelector('.preview-text');
    assert(await page.$('.password-input'));
    await page.screenshot({
      path: join(output, `${width}-${theme}-preview.png`)
    });
    results.push({
      width,
      theme,
      geometry
    });
  }
  assert.equal(errors.length, 0);
  await writeFile(join(output, 'results.json'), JSON.stringify({
    passed: true,
    scope: 'Real Uni H5 component; synthetic API only; no backend or installed desktop',
    results,
    errors
  }, null, 2));
  console.log(JSON.stringify({
    passed: true,
    output,
    variants: results.length
  }));
} finally {
  await browser.close();
  server.closeAllConnections();
  await new Promise(r => server.close(r));
  await rm(built.workspace, {
    recursive: true,
    force: true
  });
}
