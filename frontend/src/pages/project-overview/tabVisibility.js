// 中间列标签页的可见性契约（dev-board#394）。
//
// 标签页是常驻的：它与左栏当前停在哪个面板（资源管理器 / 项目概览 / 插件中心 /
// 日历 / 版本 / 尽调 …）没有耦合，也不与右栏耦合。历史上这里是一张按 leftPaneKey
// 放行的白名单（最初只放 'files'，之后每发现一个功能「点了没反应」就补一项：
// 搜索、语音、诉讼可视化、版本对比、插件广场详情、设置、停靠面板……），
// 名单之外的面板一律把全部文档标签 v-show 藏死、编辑区退成「左侧空闲」——
// 律师点一下插件中心，正在改的催款函就凭空没了。
//
// 现在的规则只有一条：只要标签存在就可见。左栏切换只改左栏内容。
// 保留这个函数（而不是直接删掉 v-show）是为了把契约钉在一个可单测的纯函数上，
// 以后谁想再加「某面板下藏标签」，先来这里改测试。
export function isTabVisibleInPane(file /* , leftPaneKey */) {
  return !!file
}
